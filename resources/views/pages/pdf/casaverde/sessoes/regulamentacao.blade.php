    <div style="font-size:10px; line-height:1.5; color:#5B6F60; text-align:justify;">
        A LEI Nº 14.300, DE 6 DE JANEIRO DE 2022, institui o marco legal da microgeração
        e minigeração distribuída e o Sistema de Compensação de Energia Elétrica (créditos de energia),
        sendo também conhecida por lei de incentivo a energia solar. A RESOLUÇÃO NORMATIVA ANEEL Nº 1.059,
        DE 7 DE FEVEREIRO DE 2023, regulamenta essa lei e estabelece as condições gerais de acesso de
        micro e minigeração distribuída aos sistemas de distribuição de energia elétrica, tendo revogado
        as antigas Resoluções Normativas ANEEL nº 482/2012 e nº 687/2015.<br><br>

        Conforme o cronograma de transição previsto na Lei 14.300/2022, a energia
        injetada na rede e compensada está sujeita à cobrança progressiva da Tarifa de Uso do Sistema de
        Distribuição referente ao Fio B, com percentual de incidência crescente entre 2023 e 2029, exceto
        para unidades consumidoras com solicitação de acesso protocolada antes de 7 de janeiro de 2023,
        que possuem direito adquirido às regras anteriores.<br><br>

        O projeto e a instalação do sistema seguem os requisitos técnicos das normas
        ABNT NBR 16690 (instalações elétricas de arranjos fotovoltaicos) e ABNT NBR 16274 (sistemas
        fotovoltaicos conectados à rede – documentação, comissionamento, inspeção e avaliação de
        desempenho). A LEI 13.169 de 06/10/15 reduz a zero as alíquotas de PIS/Pasep e COFINS incidentes
        sobre a energia elétrica ativa injetada na rede nos termos do Sistema de Compensação de Energia
        Elétrica, conforme regulamentação da ANEEL.<br><br>

        A LEI 13.709 (LGPD) diz respeito à proteção de dados pessoais. Os dados coletados possuem a
        finalidade específica de procedimentos preliminares e elaboração e execução do contrato de compra
        e venda, coletados mediante consentimento livre, informado e inequívoco do titular. Ao assinar o
        presente documento, declaro que ACEITO a proposta acima e autorizo a CASA VERDE (SOLMAR ENERGIA
        SOLAR LTDA) a utilizar meus dados pessoais para os fins destacados.
